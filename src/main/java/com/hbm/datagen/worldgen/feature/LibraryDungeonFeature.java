    @Override
    public boolean place(FeaturePlaceContext<NoneFeatureConfiguration> context) {
        WorldGenLevel level = context.level();
        BlockPos origin = context.origin();
        RandomSource rand = context.random();

        int x = origin.getX();
        int y = origin.getY();
        int z = origin.getZ();

        if (!locationIsValidSpawn(level, x, y, z)
                || !locationIsValidSpawn(level, x + 8, y, z)
                || !locationIsValidSpawn(level, x + 8, y, z + 10)
                || !locationIsValidSpawn(level, x, y, z + 10)) {
            return false;
        }

        return generate_r0(level, rand, x, y, z);
    }

