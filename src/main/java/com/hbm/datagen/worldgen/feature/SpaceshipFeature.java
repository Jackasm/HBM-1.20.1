    private boolean isValidSpawn(WorldGenLevel level, BlockPos pos) {
        BlockState checkBlock = level.getBlockState(pos.below());
        BlockState blockBelow = level.getBlockState(pos.below(2));

        List<Block> validBlocks = List.of(
                Blocks.GRASS_BLOCK, Blocks.DIRT, Blocks.STONE, Blocks.SAND, Blocks.SANDSTONE
        );

        for (Block block : validBlocks) {
            if (checkBlock.is(block)) {
                return true;
            } else if (checkBlock.is(Blocks.SNOW) && blockBelow.is(block)) {
                return true;
            } else if (checkBlock.canBeReplaced() && blockBelow.is(block)) {
                return true;
            }
        }
        return false;
    }

    @Override
    public boolean place(FeaturePlaceContext<NoneFeatureConfiguration> context) {
        WorldGenLevel level = context.level();
        BlockPos origin = context.origin();
        RandomSource rand = context.random();

        int x = origin.getX();
        int z = origin.getZ();
        int y = level.getHeight(Heightmap.Types.WORLD_SURFACE_WG, x, z);

        BlockPos pos = new BlockPos(x, y, z);

        if (!isValidSpawn(level, pos)
                || !isValidSpawn(level, pos.offset(12, 0, 0))
                || !isValidSpawn(level, pos.offset(0, 0, 23))
                || !isValidSpawn(level, pos.offset(12, 0, 23))) {
            return false;
        }

        // В оригинале y += 1 после валидации
        generateStructure(level, rand, pos.getX(), y + 1, pos.getZ());
        return true;
    }

