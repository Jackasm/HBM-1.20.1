    private void set(WorldGenLevel level, int x, int y, int z, BlockState state) {
        if (y >= level.getMinBuildHeight() && y < level.getMaxBuildHeight()) {
            level.setBlock(new BlockPos(x, y, z), state, 2);
        }
    }

    private static BlockState vine(int meta) {
        return Blocks.VINE.defaultBlockState()
                .setValue(VineBlock.SOUTH, (meta & 1) != 0)
                .setValue(VineBlock.WEST,  (meta & 2) != 0)
                .setValue(VineBlock.NORTH, (meta & 4) != 0)
                .setValue(VineBlock.EAST,  (meta & 8) != 0);
    }

    private void setStairs(WorldGenLevel level, int x, int y, int z, int meta, Block stairs) {
        Direction facing = switch (meta & 3) {
            case 0 -> Direction.EAST;
            case 1 -> Direction.WEST;
            case 2 -> Direction.SOUTH;
            default -> Direction.NORTH;
        };
        Half half = (meta & 4) != 0 ? Half.TOP : Half.BOTTOM;
        set(level, x, y, z, stairs.defaultBlockState()
                .setValue(StairBlock.FACING, facing)
                .setValue(StairBlock.HALF, half));
    }

    private static BlockState pole(int meta) {
        Direction facing = switch (meta) {
            case 2 -> Direction.NORTH;
            case 3 -> Direction.SOUTH;
            case 4 -> Direction.WEST;
            case 5 -> Direction.EAST;
            default -> Direction.NORTH;
        };
        return ModBlocks.STEEL_POLES.get().defaultBlockState().setValue(DecoSteelPoles.FACING, facing);
    }

    private static void placeDummyable(WorldGenLevel level, Block block, int x, int y, int z, int meta) {
        if (!(block instanceof BlockDummyable dummy)) return;
        int offset = meta - 10;
        Direction facing = switch (offset) {
            case 2 -> Direction.NORTH;
            case 3 -> Direction.SOUTH;
            case 4 -> Direction.WEST;
            case 5 -> Direction.EAST;
            default -> Direction.NORTH;
        };
        BlockPos corePos = new BlockPos(x, y, z);
        level.setBlock(corePos, dummy.getCoreState(facing), 3);
        dummy.placeMultiblock(level, corePos, facing);
    }

    private void setDoor(WorldGenLevel level, int x, int y, int z, Direction facing, Block door) {
        set(level, x, y, z, door.defaultBlockState()
                .setValue(DoorBlock.FACING, facing)
                .setValue(DoorBlock.HALF, DoubleBlockHalf.LOWER));
        set(level, x, y + 1, z, door.defaultBlockState()
                .setValue(DoorBlock.FACING, facing)
                .setValue(DoorBlock.HALF, DoubleBlockHalf.UPPER));
    }

    private void setChest(WorldGenLevel level, RandomSource rand, int x, int y, int z,
                          Direction facing, String poolName, int rolls) {
        BlockPos pos = new BlockPos(x, y, z);
        set(level, x, y, z, Blocks.CHEST.defaultBlockState().setValue(ChestBlock.FACING, facing));
        BlockEntity te = level.getBlockEntity(pos);
        if (te instanceof ChestBlockEntity chest) {
            ItemPool pool = ItemPool.getPool(poolName);
            for (ItemStack stack : pool.generate(rand, rolls)) {
                for (int slot = 0; slot < chest.getContainerSize(); slot++) {
                    if (chest.getItem(slot).isEmpty()) {
                        chest.setItem(slot, stack);
                        break;
                    }
                }
            }
        }
    }
