package com.hbm.blocks;

/**
 * Блок-источник радиации, который тикает сам (#198).
 *
 * <p>В 1.7.10 постановка блока в мире вызывала {@code onBlockAdded}, и источник
 * планировал свой первый тик. В 1.20.1 генерация пишет блоки через
 * {@code WorldGenRegion.setBlock}, side-эффекты не запускаются: {@code onPlace}
 * не вызывается, тик не планируется, и поставленный генерацией источник молчит.</p>
 *
 * <p>Поэтому такие блоки помечаются этим интерфейсом: при загрузке чанка
 * {@code RadiationSourceTicker} находит их по палитре секций и планирует первый
 * тик. Дальше блок перепланирует себя сам, как и раньше.</p>
 */
public interface IRadiationSource {

    /** Даёт ли этот блок радиацию — чтобы не сканировать секции с пустышками. */
    boolean emitsRadiation();
}
